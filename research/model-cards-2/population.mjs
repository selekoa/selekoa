// Later packs: round robin over the developers in fixed order; each turn takes that
// developer's earliest-dated card with status "in". Pending cards join the order at the
// first pack after they are retrieved or decided: a row's eighth element is that pack, and
// the row is not taken for an earlier one (the three places resolved by the cross-family
// check of 2026-11-04 join from pack 3; completed pack 2 is unchanged). Undated cards
// ("not located") go last.
const rank = (d) => (/^\d/.test(d) ? d : '9999');
const queue = Object.fromEntries(
  DEVS.map((dev) => [
    dev,
    P.filter((r) => r[0] === dev && r[4] === 'in').sort((a, b) =>
      rank(a[2]).localeCompare(rank(b[2])),
    ),
  ]),
);
const order = [];
while (DEVS.some((d) => queue[d].length))
  for (const d of DEVS) {
    const pack = 2 + Math.floor(order.length / 8);
    const i = queue[d].findIndex((r) => (r[7] ?? 0) <= pack);
    if (i >= 0) order.push(queue[d].splice(i, 1)[0]);
  }
const packOf = new Map(order.map((r, i) => [r, 2 + Math.floor(i / 8)]));
const rows = P.map((r) => ({
  developer: r[0],
  card: r[1],
  earliestLocated: r[2],
  dateKind: r[3],
  status: r[4],
  basis: r[5],
  cacheKey: r[6],
  ...(r[7] ? { joinsFromPack: r[7] } : {}),
  pack: r[4] === 'row1' ? 1 : (packOf.get(r) ?? null),
}));
writeFileSync(
  join(DIR, 'population.json'),
  JSON.stringify(
    { generated: 'node research/model-cards-2/population.mjs', rows },
    null,
    2,
  ) + '\n',
);
