// Builds the item list for the cross-family archive verification of 2026-10-28.
// Usage: node research/archive-verification-2026-10-28/build.mjs
// Reads data/sources.json and data/evidence.json; writes items.json and items.md here.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..', '..');
const read = (f) => JSON.parse(readFileSync(join(ROOT, 'data', f), 'utf8'));
const sources = read('sources.json');
const evidence = read('evidence.json');

// Hosts whose documents are versioned or archival: a capture adds little.
const STABLE = new Set([
  'arxiv.org',
  'export.arxiv.org',
  'www.nber.org',
  'www.aeaweb.org',
  'www.sec.gov',
  'archive.org',
  'web.archive.org',
  'doi.org',
  'eur-lex.europa.eu',
  'op.europa.eu',
  'publications.europa.eu',
  'www.govinfo.gov',
  'www.federalregister.gov',
]);
// Version notes that say a cited capture was not opened or could not be checked.
const UNOPENED =
  /availability|unchecked|not (opened|checked|inspected|retrieved)|refused|unreachable|429|reset/i;

const quotes = (id) =>
  evidence
    .filter((e) => e.sourceId === id && e.passageType === 'quote')
    .map((e) => ({ id: e.id, locator: e.locator, passage: e.passage }));
const paraphrases = (id) =>
  evidence.filter((e) => e.sourceId === id && e.passageType === 'paraphrase')
    .length;

const items = [];
for (const s of sources) {
  const host = new URL(s.evidenceUrl).host;
  let group;
  if (s.archivedUrl)
    group = UNOPENED.test(s.version)
      ? 'A1-capture-unopened'
      : 'A2-capture-cited';
  else if (!STABLE.has(host)) group = 'B-no-capture';
  else continue;
  items.push({
    n: 0,
    group,
    source: s.id,
    title: s.title,
    kind: s.kind,
    url: s.evidenceUrl,
    accessedAt: s.accessedAt,
    archivedUrl: s.archivedUrl ?? null,
    archivedAt: s.archivedAt ?? null,
    quotes: quotes(s.id),
    paraphraseCount: paraphrases(s.id),
  });
}
const order = ['A1-capture-unopened', 'A2-capture-cited', 'B-no-capture'];
items.sort(
  (a, b) =>
    order.indexOf(a.group) - order.indexOf(b.group) ||
    a.source.localeCompare(b.source),
);
items.forEach((it, i) => (it.n = i + 1));

writeFileSync(join(HERE, 'items.json'), JSON.stringify(items, null, 2) + '\n');
const count = (g) => items.filter((i) => i.group === g);
const lines = [
  '# Archive verification items, 2026-10-28',
  '',
  'Generated by `node research/archive-verification-2026-10-28/build.mjs` from `data/`; do not edit by hand. Full records, with every quotation to check, are in `items.json`.',
  '',
  '| Group | Meaning | Sources | Quotations |',
  '| --- | --- | ---: | ---: |',
  ...order.map((g) => {
    const xs = count(g);
    const meaning = {
      'A1-capture-unopened':
        'Capture cited, but the source record says it was not opened or could not be checked',
      'A2-capture-cited': 'Capture cited',
      'B-no-capture': 'No capture cited; mutable host',
    }[g];
    return `| ${g} | ${meaning} | ${xs.length} | ${xs.reduce((n, x) => n + x.quotes.length, 0)} |`;
  }),
  '',
  '| # | Group | Source | Kind | Accessed | Quotations |',
  '| ---: | --- | --- | --- | --- | ---: |',
  ...items.map(
    (i) =>
      `| ${i.n} | ${i.group.slice(0, 2)} | \`${i.source}\` | ${i.kind} | ${i.accessedAt} | ${i.quotes.length} |`,
  ),
  '',
];
writeFileSync(join(HERE, 'items.md'), lines.join('\n'));
