  '',
  'Texts dated up to 2026-11-02, **including texts before 2016**, by the named bodies only: the BIS (with the Innovation Hub, the FSI, the IFC and the Basel Committee), the FSB, the IMF, IOSCO, the ESRB, the EBA, EIOPA; the ECB and ECB Banking Supervision, the Bank of England (with the PRA and FCA), the Bank of Finland, the Bundesbank, the Riksbank, other Eurosystem and Nordic central banks; the Federal Reserve Board, the PBoC, the Bank of Japan, MAS, HKMA and the RBI. Securities regulators enter only through IOSCO (decision 10a); central banks outside this list are not recorded (decision 16a), but name any you find as leads. Reports, guidance, consultation papers, bulletins, staff papers in the bodies’ own series, and speeches or testimony by their officials. No press, no Wikipedia. Say what you searched.',
