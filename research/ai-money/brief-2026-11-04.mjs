  '',
  '**Report files.** Write `research/ai-money/cross-family-check-2026-11-04.md` and `research/ai-money/cross-family-check-2026-11-04.json` on your own branch `codex/ai-money-check-2`, from `ai-money-pack-2`. Change no other file; open no pull request.',
  '',
  '## How to work',
  '',
