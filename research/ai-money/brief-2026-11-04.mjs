// Short cross-family brief for the records new or changed after the maintainer decisions and
// the follow-up pass of 2026-11-04. Blind first (Parts A1 and A2), then direct (Part B) and
// retrieval (Part C); the pack's answers go to a separate verdicts file.
//   node research/ai-money/brief-2026-11-04.mjs
// Writes cross-family-input-2026-11-04.md and cross-family-verdicts-2026-11-04.json.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = dirname(fileURLToPath(import.meta.url));
const DATE = '2026-11-04';
// Evidence notes that name a stance would unblind Part A2; they are left out there.
const STANCE_WORDS = /stance|contest|articulat|bears on|context/i;
const pack = JSON.parse(readFileSync(join(DIR, 'pack.json'), 'utf8'));
const props = new Map(pack.propositions.map((p) => [p.code, p]));
const docs = new Map(pack.documents.map((d) => [d.id, d]));
const srcs = new Map(pack.sources.map((s) => [s.key, s]));
const rec = (id) => {
  const r = pack.records.find((x) => x.id === id);
  if (!r) throw new Error(`no record ${id}`);
  return r;
};
const evt = (id) => {
  const e = pack.events.find((x) => x.id === id);
  if (!e) throw new Error(`no event ${id}`);
  return e;
};
const docLine = (d) =>
  `${d.title} — ${d.voice === 'institution' ? d.institution : `${d.authors.join(', ')}${d.speakerRole ? `, ${d.speakerRole}` : ''} (${d.institution})`}; ${d.subtype.toLowerCase()}; voice: ${d.voice}; dated ${d.date} (${d.dateBasis})${d.disclaimer ? `; disclaimer (${d.disclaimer.locator}): “${d.disclaimer.passage}”` : ''}`;
const crit = (code) =>
  `**${code}.** ${props.get(code).label}. ${props.get(code).criterion}`;
// Seeded order (linear congruential generator, as in build.mjs).
const shuffle = (xs, seed) => {
  let s = seed >>> 0;
  const r = () => (s = (Math.imul(s, 1664525) + 1013904223) >>> 0) / 2 ** 32;
  const a = [...xs];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(r() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
};

