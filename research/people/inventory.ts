// Inventory for the people pack: single-record authors and persons without a role record.
// Run: pnpm exec tsx research/people/inventory.ts  → research/people/inventory.json
// Name matching follows research/author-persons/inventory.ts (family name and first given word).
import { readFileSync, writeFileSync } from 'node:fs';

const read = (f: string) => JSON.parse(readFileSync(`data/${f}.json`, 'utf8'));
type Name = { family?: string; given?: string; literal?: string };
type Source = {
  id: string;
  title: string;
  authors: string[];
  authorNames?: Name[];
  documentId?: string;
  publicationDate?: string | null;
};
type Entity = {
  id: string;
  name: string;
  type: string;
  subtype?: string;
  sortName?: string;
  aliases?: string[];
  sourceIds?: string[];
  description?: string;
};
type Claim = {
  id: string;
  subject: string;
  predicate: string;
  object: { kind: string; entityId?: string };
};
const entities: Entity[] = read('entities');
const claims: Claim[] = read('claims');
const sources: Source[] = read('sources');

const fold = (s: string) =>
  s
    .normalize('NFKD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z一-鿿 ]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
function key(family: string, given = '') {
  const g = fold(given)
    .split(' ')
    .filter((w) => w.length > 1);
  return `${fold(family)}|${g[0] ?? fold(given).split(' ')[0] ?? ''}`;
}
const keyFromFull = (full: string) => {
  const w = full.trim().split(/\s+/);
  return key(w[w.length - 1], w.slice(0, -1).join(' '));
};

const byId = new Map(entities.map((e) => [e.id, e]));
const persons = entities.filter((e) => e.type === 'person');
const personKeys = new Map<string, string>();
for (const p of persons) {
  if (p.sortName?.includes(',')) {
    const [f, g] = p.sortName.split(',');
    personKeys.set(key(f, g), p.id);
  }
  for (const n of [p.name, ...(p.aliases ?? [])])
    personKeys.set(keyFromFull(n), p.id);
}
const docOfSource = new Map<string, string>();
for (const s of sources) if (s.documentId) docOfSource.set(s.id, s.documentId);
for (const e of entities)
  if (e.type === 'document')
    for (const sid of e.sourceIds ?? [])
      if (!docOfSource.has(sid)) docOfSource.set(sid, e.id);

type Row = {
  key: string;
  forms: Set<string>;
  sources: Set<string>;
  documents: Set<string>;
  positions: { source: string; position: number; of: number }[];
};
const rows = new Map<string, Row>();
for (const s of sources)
  (s.authorNames ?? []).forEach((n, i, all) => {
    if (!n.family) return;
    const k = key(n.family, n.given);
    if (personKeys.has(k)) return;
    const r = rows.get(k) ?? {
      key: k,
      forms: new Set<string>(),
      sources: new Set<string>(),
      documents: new Set<string>(),
      positions: [],
    };
    r.forms.add((s.authors[i] ?? `${n.given ?? ''} ${n.family}`).trim());
    r.sources.add(s.id);
    const doc = docOfSource.get(s.id);
    if (doc) r.documents.add(doc);
    r.positions.push({ source: s.id, position: i + 1, of: all.length });
    rows.set(k, r);
  });

const singleRecordAuthors = [...rows.values()]
  .filter((r) => r.documents.size === 1)
  .map((r) => {
    const doc = [...r.documents][0];
    return {
      key: r.key,
      forms: [...r.forms],
      document: doc,
      documentTitle: byId.get(doc)?.name ?? null,
      sources: [...r.sources],
      positions: r.positions,
    };
  })
  .sort(
    (a, b) =>
      a.document.localeCompare(b.document) ||
      a.positions[0].position - b.positions[0].position,
  );
const evidenceOnly = [...rows.values()]
  .filter((r) => r.documents.size === 0)
  .map((r) => ({ key: r.key, forms: [...r.forms], sources: [...r.sources] }));
const multiDocument = [...rows.values()]
  .filter((r) => r.documents.size > 1)
  .map((r) => ({
    key: r.key,
    forms: [...r.forms],
    documents: [...r.documents],
  }));

const roleSubjects = new Set(
  claims.filter((c) => c.predicate === 'held_role').map((c) => c.subject),
);
const personsWithoutRole = persons
  .filter((p) => !roleSubjects.has(p.id))
  .map((p) => ({
    id: p.id,
    name: p.name,
    subtype: p.subtype,
    description: p.description,
    claims: claims
      .filter((c) => c.subject === p.id || c.object.entityId === p.id)
      .map((c) => `${c.id} (${c.predicate})`),
  }));

writeFileSync(
  'research/people/inventory.json',
  JSON.stringify(
    {
      note: 'Generated by inventory.ts from data/ at the pack baseline; counts are the pack’s, not the current dataset’s.',
      singleRecordAuthors,
      evidenceOnlyBylines: evidenceOnly,
      multiDocumentAuthorsWithoutRecord: multiDocument,
      personsWithoutRole: {
        excludingWriters: personsWithoutRole.filter(
          (p) => p.subtype !== 'Writer',
        ),
        writers: personsWithoutRole
          .filter((p) => p.subtype === 'Writer')
          .map((p) => p.id),
      },
    },
    null,
    1,
  ) + '\n',
);
console.log(
  'single-record authors',
  singleRecordAuthors.length,
  'evidence-only bylines',
  evidenceOnly.length,
  'multi-document without record',
  multiDocument.length,
  'persons without role (non-writer)',
  personsWithoutRole.filter((p) => p.subtype !== 'Writer').length,
);
