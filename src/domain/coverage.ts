import { dateOf, isPropositionRecord } from './query';
import { isAssessment, type Claim, type Dataset, type Entity } from './schema';

const tally = <K extends string>(keys: K[], values: K[]) =>
  Object.fromEntries(
    keys.map((k) => [k, values.filter((v) => v === k).length]),
  ) as Record<K, number>;

/**
 * Coverage computed from the stored records. The About page and the generated
 * README block both use it, so no current count is copied by hand.
 */
export function coverage(data: Dataset) {
  const types = Object.entries(
    data.entities.reduce<Record<string, number>>((n, e) => {
      n[e.type] = (n[e.type] ?? 0) + 1;
      return n;
    }, {}),
  ).sort((a, b) => b[1] - a[1]) as [Entity['type'], number][];
  const years = data.claims
    .map(dateOf)
    .filter((d): d is string => Boolean(d))
    .map((d) => d.slice(0, 4))
    .sort();
  const checks = data.evidence.map((e) => e.checkedAt).sort();
  const relationships = data.claims.filter(
    (c) => c.object.kind === 'entity',
  ).length;
  const humanReviewed = data.evidence.filter(
    (e) => e.verification === 'human_reviewed',
  ).length;
  const accepted = data.claims.filter(
    (c) => c.editorialState === 'accepted',
  ).length;
  return {
    schemaVersion: data.meta.schemaVersion,
    updatedAt: data.meta.updatedAt,
    entities: data.entities.length,
    types,
    claims: data.claims.length,
    relationships,
    values: data.claims.length - relationships,
    propositionRecords: data.claims.filter(isPropositionRecord).length,
    provisions: data.claims.filter((c) => c.predicate === 'states_provision')
      .length,
    absences: data.claims.filter((c) => c.predicate === 'provision_not_found')
      .length,
    assessments: data.claims.filter(isAssessment).length,
    sources: data.sources.length,
    evidence: data.evidence.length,
    firstCheck: checks[0],
    lastCheck: checks.at(-1)!,
    firstYear: years[0],
    lastYear: years.at(-1)!,
    undated: data.claims.filter((c) => c.time.kind === 'unknown').length,
    derivation: tally<Claim['derivation']>(
      ['explicit', 'inferred', 'posed'],
      data.claims.map((c) => c.derivation),
    ),
    resolution: tally<Claim['resolution']>(
      ['supported', 'contested', 'unresolved'],
      data.claims.map((c) => c.resolution),
    ),
    accepted,
    seed: data.claims.length - accepted,
    humanReviewed,
    machineChecked: data.evidence.length - humanReviewed,
  };
}
export type Coverage = ReturnType<typeof coverage>;

const n = (value: number) => value.toLocaleString('en-US');
const plural = (value: number, one: string, many = one + 's') =>
  `${n(value)} ${value === 1 ? one : many}`;

export const coverageStart =
  '<!-- coverage:start — generated by `pnpm docs:coverage` from the stored records; do not edit by hand -->';
export const coverageEnd = '<!-- coverage:end -->';

/** The README's current-coverage paragraph, between its markers. */
export function coverageMarkdown(c: Coverage): string {
  return [
    coverageStart,
    '',
    `The dataset (schema ${c.schemaVersion}, updated ${c.updatedAt}) contains **${plural(c.entities, 'entity', 'entities')}, ${plural(c.claims, 'claim')}, ${plural(c.sources, 'source')} and ${plural(c.evidence, 'evidence record')}**. Claims comprise ${plural(c.relationships, 'relationship')} between records, including ${plural(c.propositionRecords, 'record')} of a text articulating, contesting or bearing on a proposition, and ${plural(c.values, 'claim')} about a value, including ${plural(c.provisions, 'quoted provision')} of frameworks, laws, commitment texts and governing documents and ${plural(c.absences, 'recorded absence')}. Dated records run from ${c.firstYear} to ${c.lastYear}; ${plural(c.undated, 'record has', 'records have')} no established date. Evidence checks span ${c.firstCheck} to ${c.lastCheck}.`,
    '',
    `By derivation, ${n(c.derivation.explicit)} claims are stated in a source, ${n(c.derivation.inferred)} are inferred and ${n(c.derivation.posed)} are questions posed by Selekoa; ${plural(c.assessments, 'claim is an assessment', 'claims are assessments')} of a change, a provision or control. ${n(c.resolution.supported)} are supported, ${n(c.resolution.contested)} contested (with evidence on both sides) and ${n(c.resolution.unresolved)} unresolved (context evidence only). There ${c.seed === 1 ? 'is' : 'are'} **${plural(c.seed, 'seed claim')} and ${plural(c.accepted, 'editorially accepted claim')}; ${plural(c.machineChecked, 'machine-checked evidence record')} and ${plural(c.humanReviewed, 'human-reviewed record')}**.`,
    '',
    coverageEnd,
  ].join('\n');
}

/** Replaces the generated block in a document; throws if the markers are missing. */
export function withCoverage(document: string, block: string): string {
  const start = document.indexOf('<!-- coverage:start');
  const end = document.indexOf(coverageEnd);
  if (start < 0 || end < start) throw new Error('Coverage markers not found');
  return (
    document.slice(0, start) + block + document.slice(end + coverageEnd.length)
  );
}
